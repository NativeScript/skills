#!/usr/bin/env node
// Prepares the skillgrade suite:
//   evals/suite/skills/<name>/   flattened copy of every skill (skillgrade 0.2.x
//                                only detects skills/<name>/SKILL.md one level deep)
//   evals/suite/eval.yaml        rendered from evals/tasks.mjs, skills on
//   evals/baseline/eval.yaml     identical tasks, no skills (skill: ./empty)
// Run via evals/run.sh. The YAML files are generated — edit tasks.mjs instead.
import fs from 'node:fs';
import path from 'node:path';
import { root, discoverSkills } from '../lib/skills.mjs';
import { tasks } from './tasks.mjs';

const suiteDir = path.join(root, 'evals/suite');
const baselineDir = path.join(root, 'evals/baseline');
const staged = path.join(suiteDir, 'skills');

fs.rmSync(staged, { recursive: true, force: true });
fs.mkdirSync(staged, { recursive: true });
const skills = discoverSkills();
for (const s of skills) fs.cpSync(s.dir, path.join(staged, s.name), { recursive: true, filter: (p) => !p.endsWith('.DS_Store') });
fs.mkdirSync(path.join(baselineDir, 'empty'), { recursive: true });

const block = (s, indent) => {
  const pad = ' '.repeat(indent);
  return '|\n' + s.replace(/\s+$/, '').split('\n').map((l) => (l.trim() ? pad + l : '')).join('\n') + '\n';
};
const q = (s) => JSON.stringify(s);

function render({ baseline }) {
  // Both eval.yaml files sit one directory under evals/, so repo-relative fixture paths need ../../
  const rel = '../../';
  const out = [];
  out.push(`# GENERATED by evals/build.mjs from evals/tasks.mjs — do not edit.`);
  out.push(`# Run with evals/run.sh (sets SKILLGRADE_REPO and uses the local provider).`);
  out.push(baseline ? `# Baseline: identical tasks with NO skills installed, to measure uplift.` : `# Every skill under ../../skills (flattened into ./skills by build.mjs) is copied into each trial's workspace.`);
  out.push(`version: "1"`);
  if (baseline) out.push(`skill: ./empty`);
  out.push(``);
  out.push(`defaults:`);
  out.push(`  agent: command`);
  out.push(`  command: bash "$SKILLGRADE_REPO/evals/agent/claude-cli.sh"`);
  out.push(`  provider: local`);
  out.push(`  trials: 3`);
  out.push(`  timeout: 900`);
  out.push(`  threshold: 0.7`);
  out.push(`  grader_provider: anthropic`);
  out.push(``);
  out.push(tasks.length ? `tasks:` : `tasks: []`);
  for (const t of tasks) {
    out.push(`  - name: ${t.name}`);
    out.push(`    instruction: ${block(t.instruction, 6)}`);
    if (t.workspace?.length) {
      out.push(`    workspace:`);
      for (const w of t.workspace) out.push(`      - src: ${q(rel + w.src)}\n        dest: ${q(w.dest)}`);
    }
    out.push(`    graders:`);
    out.push(`      - type: deterministic`);
    out.push(`        run: node "$SKILLGRADE_REPO/evals/graders/check.mjs" ${t.name}`);
    out.push(`        weight: 0.7`);
    out.push(`      - type: llm_rubric`);
    out.push(`        rubric: ${block(t.rubric, 10)}`);
    out.push(`        weight: 0.3`);
    out.push(``);
  }
  return out.join('\n');
}

fs.writeFileSync(path.join(suiteDir, 'eval.yaml'), render({ baseline: false }));
fs.writeFileSync(path.join(baselineDir, 'eval.yaml'), render({ baseline: true }));
console.log(`staged ${skills.length} skills → evals/suite/skills; wrote evals/suite/eval.yaml + evals/baseline/eval.yaml (${tasks.length} tasks)`);
