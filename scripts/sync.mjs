#!/usr/bin/env node
// Regenerates everything that enumerates skills or categories, from the tree:
//   skills.sh.json                 groupings = leaf categories, titled by each README's heading
//   .claude-plugin/plugin.json     skills = every directory that directly contains skills
//   .claude-plugin/marketplace.json  (Claude Code scans a listed directory one level deep)
//   README.md                      the skills table between <!-- skills:start --> / <!-- skills:end -->
//   node scripts/sync.mjs          write
//   node scripts/sync.mjs --check  exit 1 if anything is out of date (CI)
import fs from 'node:fs';
import path from 'node:path';
import { root, discover, readSkill } from '../lib/skills.mjs';

const check = process.argv.includes('--check');
const { skills, categories } = discover();
const leaf = categories.filter((c) => c.skills.length);
let stale = [];

function write(rel, content) {
  const file = path.join(root, rel);
  const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (cur === content) return;
  if (check) { stale.push(rel); return; }
  fs.writeFileSync(file, content);
  console.log(`wrote ${rel}`);
}
const json = (o) => JSON.stringify(o, null, 2) + '\n';
const readJson = (rel) => JSON.parse(fs.readFileSync(path.join(root, rel), 'utf8'));

// skills.sh.json — one group per leaf category, in tree order.
write('skills.sh.json', json({
  $schema: 'https://skills.sh/schema/skills.sh.json',
  notGrouped: 'bottom',
  groupings: leaf.map((c) => ({ title: c.title, description: c.description, skills: c.skills })),
}));

// Claude Code plugin manifests — list each leaf directory; the default skills/ scan
// only sees skills/<name>/SKILL.md, which a categorised tree never has.
const skillDirs = leaf.map((c) => `./skills/${c.rel}/`);
const plugin = readJson('.claude-plugin/plugin.json');
plugin.skills = skillDirs;
write('.claude-plugin/plugin.json', json(plugin));
const marketplace = readJson('.claude-plugin/marketplace.json');
for (const p of marketplace.plugins) if (p.name === plugin.name) p.skills = skillDirs;
write('.claude-plugin/marketplace.json', json(marketplace));

// README table.
const readmePath = path.join(root, 'README.md');
const readme = fs.readFileSync(readmePath, 'utf8');
const start = '<!-- skills:start -->', end = '<!-- skills:end -->';
const a = readme.indexOf(start), b = readme.indexOf(end);
if (a < 0 || b < 0) { console.error('README.md lacks <!-- skills:start --> / <!-- skills:end --> markers'); process.exit(2); }
let table = `\n_${skills.length} skill${skills.length === 1 ? '' : 's'} in ${leaf.length} categor${leaf.length === 1 ? 'y' : 'ies'}. Generated by \`npm run sync\` from the \`skills/\` tree and each category's README._\n`;
if (!skills.length) table += `\nNo skills yet — see [CONTRIBUTING.md](CONTRIBUTING.md) to add the first one.\n`;
for (const c of leaf) {
  table += `\n### ${c.title} <sub>\`skills/${c.rel}/\`</sub>\n\n${c.description}\n\n| Skill | Use it when… |\n|---|---|\n`;
  for (const name of c.skills) {
    const s = skills.find((x) => x.name === name);
    const desc = (readSkill(s).fm?.description || '').replace(/^Use when\s+/i, '').replace(/\|/g, '\\|').trim();
    table += `| [\`${name}\`](skills/${s.rel}/SKILL.md) | ${desc} |\n`;
  }
}
write('README.md', readme.slice(0, a + start.length) + '\n' + table + '\n' + readme.slice(b));

if (check) {
  if (stale.length) { console.error(`out of date (run \`npm run sync\`): ${stale.join(', ')}`); process.exit(1); }
  console.log(`manifests in sync (${skills.length} skills, ${leaf.length} categories)`);
}
